// Геометрия предмета в процентах от сцены + маска и позиция «копии фона».
export function geometry(o) {
  const xs = o.points.map((p) => p[0]), ys = o.points.map((p) => p[1]);
  const pad = 0;
  const x0 = Math.max(0, Math.min(...xs) - pad), y0 = Math.max(0, Math.min(...ys) - pad);
  const x1 = Math.min(STAGE.w, Math.max(...xs) + pad), y1 = Math.min(STAGE.h, Math.max(...ys) + pad);
  const bw = x1 - x0, bh = y1 - y0;
  const pct = (v, t) => +(v / t * 100).toFixed(3);
  const left = pct(x0, STAGE.w), top = pct(y0, STAGE.h), width = pct(bw, STAGE.w), height = pct(bh, STAGE.h);
  const poly = 'polygon(' + o.points.map(([x, y]) => `${pct(x - x0, bw)}% ${pct(y - y0, bh)}%`).join(',') + ')';
  const bgW = +(10000 / width).toFixed(3), bgH = +(10000 / height).toFixed(3);
  const bgX = width >= 100 ? 0 : +(left / (100 - width) * 100).toFixed(3);
  const bgY = height >= 100 ? 0 : +(top / (100 - height) * 100).toFixed(3);
  return { left, top, width, height, poly, bgSize: `${bgW}% ${bgH}%`, bgPos: `${bgX}% ${bgY}%`,
    cx: pct((x0 + x1) / 2, STAGE.w), cy: pct((y0 + y1) / 2, STAGE.h), tipTop: top };
}
